/**
 * The continuity artifacts of a work (issue 119): the session <-> attempt
 * association, the external-effect journal the in-container guardrail writes,
 * the verdicts handed back to the next session, and the persisted continuity pause.
 *
 * Layout decision (disk names stay PT-BR with the rest of the registry):
 *   <work dir>/sessao-vinculos.jsonl — one line per launch: work + attempt +
 *                                      round + the exact Pi session id
 *   <work dir>/efeitos.jsonl         — intents (before the action) and results
 *   <work dir>/continuidade.json     — what the host reconciled before the launch
 *   <work dir>/pausa.json            — the pause that survives a restart
 *
 * The journal is append-only and fsynced: an intent is on disk BEFORE the tool
 * runs, so a kill inside the window still leaves the fact that the action was
 * attempted. A corrupt journal is said so — never repaired into silence.
 */

import { closeSync, existsSync, fsyncSync, mkdirSync, openSync, readFileSync, renameSync, writeSync } from "node:fs";
import { dirname, join } from "node:path";

import type { EffectAction } from "./effects.js";
import type { IssueRef } from "../tracker/port.js";
import { parseJsonLine, parseJsonObject } from "./json-line.js";

export const SESSION_LINKS_FILENAME = "sessao-vinculos.jsonl";
export const EFFECT_JOURNAL_FILENAME = "efeitos.jsonl";
export const GUARDRAIL_STATE_FILENAME = "continuidade.json";
export const PAUSE_FILENAME = "pausa.json";

export interface SessionLink {
  version: 1;
  /** The work the session belongs to — its identity, never the directory name. */
  work: IssueRef;
  /** The attempt this session carries (the SAME number a recovery continues). */
  attempt: number;
  /** 1 for the attempt's first launch; a resumption of the same attempt that
   *  needs a fresh session gets the next one. */
  round: number;
  /** "new" started the session; "resume" continued an existing one. */
  mode: "new" | "resume";
  /** The Pi session id — generated by the factory before the launch. */
  sessionId: string;
  at: string;
}

/** The journal shows the session had the guardrail active before any effect. */
export interface JournalSessionStart {
  type: "session-start";
  at: string;
  attempt: number;
  sessionId: string;
}

/** Written BEFORE the action it protects. */
export interface JournalIntent {
  type: "intent";
  seq: number;
  at: string;
  attempt: number;
  sessionId: string;
  /** The Pi tool call id — the correlation with the session transcript. */
  callId: string;
  tool: string;
  command: string;
  safety: "effect" | "unknown";
  actions: EffectAction[];
  reason?: string;
}

/** Written after the action reported back; its absence is the interrupted window. */
export interface JournalResult {
  type: "result";
  seq: number;
  at: string;
  attempt: number;
  sessionId: string;
  callId: string;
  ok: boolean;
}

export type JournalLine = JournalSessionStart | JournalIntent | JournalResult;

export interface EffectJournal {
  /** False when a line did not parse: the journal cannot prove anything. */
  intact: boolean;
  sessions: JournalSessionStart[];
  intents: JournalIntent[];
  results: JournalResult[];
  /** Intents without a result — the window an interruption left open. */
  pending: JournalIntent[];
}

/** A guardrail verdict about an effect a previous round left open. */
export type EffectVerdict = "realized" | "absent";

export interface GuardrailState {
  version: 1;
  attempt: number;
  sessionId: string;
  mode: "new" | "resume";
  /** Per effect key: what the host proved against the real state. */
  verdicts: Record<string, EffectVerdict>;
  at: string;
}

/** Why a work waits for the operator instead of being recovered (issue 119).
 *  The list is the source of both the type and the runtime validation, so a
 *  reason cannot exist in one and be missing from the other. */
const PAUSE_REASONS = [
  "link-missing",
  "session-missing",
  "session-unreadable",
  "session-identity",
  "journal-unreadable",
  "effect-unsupported",
  "effect-ambiguous",
  "tool-evidence-missing",
  /** The record ITSELF cannot be read. Never written by a launch, only
   *  reported by {@link readPause}: the file says "wait" and the factory cannot
   *  read why, so it keeps waiting and asks instead of falling back to a
   *  recovery. Written back as a real pause (which closes the doubt) once the
   *  operator has been told. */
  "record-unreadable",
] as const;

export type PauseReason = (typeof PAUSE_REASONS)[number];

const KNOWN_PAUSE_REASONS: ReadonlySet<string> = new Set(PAUSE_REASONS);

export interface PauseRecord {
  version: 1;
  work: IssueRef;
  attempt: number;
  reason: PauseReason;
  /** The operator's diagnosis — paths and effect keys, never credentials. */
  detail: string;
  at: string;
  sessionId?: string;
  /** The block and the help request landed. A pause persisted without this is
   *  a pause the factory died before announcing: the next cycle must ask. */
  announced?: boolean;
}

// ---- the session association ----

/** Append a launch's association; fsynced, because a recovery may be the very
 *  next thing the factory does after a death. */
export function appendSessionLink(workDir: string, link: SessionLink): void {
  appendDurable(join(workDir, SESSION_LINKS_FILENAME), link);
}

export interface SessionLinks {
  intact: boolean;
  links: SessionLink[];
}

export function readSessionLinks(workDir: string): SessionLinks {
  const raw = readIfExists(join(workDir, SESSION_LINKS_FILENAME));
  if (raw === null) return { intact: true, links: [] };
  const links: SessionLink[] = [];
  let intact = true;
  for (const line of raw.split("\n")) {
    if (line.trim() === "") continue;
    const parsed = parseJsonLine(line);
    if (!isSessionLink(parsed)) {
      intact = false;
      continue;
    }
    links.push(parsed);
  }
  return { intact, links };
}

/** The launch a recovery continues: the LAST association recorded for the
 *  exact (work, attempt). Never the newest file, never a guess. */
export function linkForAttempt(links: readonly SessionLink[], work: IssueRef, attempt: number): SessionLink | null {
  let found: SessionLink | null = null;
  for (const link of links) {
    if (link.work.repo !== work.repo || link.work.number !== work.number) continue;
    if (link.attempt !== attempt) continue;
    if (found === null || link.round >= found.round) found = link;
  }
  return found;
}

export function nextRound(links: readonly SessionLink[], work: IssueRef, attempt: number): number {
  let round = 0;
  for (const link of links) {
    if (link.work.repo === work.repo && link.work.number === work.number && link.attempt === attempt) {
      round = Math.max(round, link.round);
    }
  }
  return round + 1;
}

// ---- the effect journal ----

/** One tool call, as the session that issued it names it. Exported because the
 *  guardrail runs in another process, on the same journal: `call-1` is unique
 *  inside its session, not across the attempt's rounds, so every reader pairs
 *  on both halves with this one rule. */
export function callKey(sessionId: string, callId: string): string {
  return `${sessionId}\u0000${callId}`;
}

export function appendJournalStart(workDir: string, entry: Omit<JournalSessionStart, "type" | "at">, at = new Date().toISOString()): void {
  appendDurable(join(workDir, EFFECT_JOURNAL_FILENAME), { type: "session-start", at, ...entry } satisfies JournalSessionStart);
}

export function appendJournalIntent(workDir: string, entry: Omit<JournalIntent, "type" | "at" | "seq">, at = new Date().toISOString()): void {
  const seq = nextSeq(readEffectJournal(workDir));
  appendDurable(join(workDir, EFFECT_JOURNAL_FILENAME), { type: "intent", seq, at, ...entry } satisfies JournalIntent);
}

export function appendJournalResult(workDir: string, entry: Omit<JournalResult, "type" | "at" | "seq">, at = new Date().toISOString()): void {
  const seq = nextSeq(readEffectJournal(workDir));
  appendDurable(join(workDir, EFFECT_JOURNAL_FILENAME), { type: "result", seq, at, ...entry } satisfies JournalResult);
}

/** Read the journal, pairing results with their intents. A partial last line
 *  counts as an incomplete write: the journal is then NOT intact, because it
 *  may have lost the intent that protects an effect. */
export function readEffectJournal(workDir: string): EffectJournal {
  const raw = readIfExists(join(workDir, EFFECT_JOURNAL_FILENAME));
  const journal: EffectJournal = { intact: true, sessions: [], intents: [], results: [], pending: [] };
  if (raw === null) return journal;

  const lines = raw.split("\n");
  const trailing = lines.pop() ?? "";
  if (trailing.trim() !== "") {
    // The file does not end with a newline: the last record was interrupted.
    journal.intact = false;
  }
  const completed = [...lines];
  for (const line of completed) {
    if (line.trim() === "") continue;
    // Widened to `unknown` so the guard narrows to exactly JournalLine: on the
    // parsed JsonValue the narrowing would be an intersection of unrelated
    // members, which no longer discriminates on `type`.
    const parsed: unknown = parseJsonLine(line);
    if (!isJournalLine(parsed)) {
      journal.intact = false;
      continue;
    }
    if (parsed.type === "session-start") journal.sessions.push(parsed);
    else if (parsed.type === "intent") journal.intents.push(parsed);
    else journal.results.push(parsed);
  }
  // A call id is unique inside its session, not across the attempt's rounds:
  // pair on both, or a later round's "call-1" would mark an earlier round's
  // "call-1" answered and hide a pending effect.
  const answered = new Set(journal.results.map((result) => callKey(result.sessionId, result.callId)));
  journal.pending = journal.intents.filter((intent) => !answered.has(callKey(intent.sessionId, intent.callId)));
  return journal;
}

function nextSeq(journal: EffectJournal): number {
  const sequences = [...journal.intents, ...journal.results].map((entry) => entry.seq);
  return sequences.reduce((max, seq) => Math.max(max, seq), 0) + 1;
}

// ---- the guardrail state handed to the next session ----

export function writeGuardrailState(workDir: string, state: GuardrailState): void {
  writeAtomic(join(workDir, GUARDRAIL_STATE_FILENAME), state);
}

export function readGuardrailState(workDir: string): GuardrailState | null {
  const raw = readIfExists(join(workDir, GUARDRAIL_STATE_FILENAME));
  if (raw === null) return null;
  const record = parseJsonObject(raw);
  if (record === null) return null;
  if (record["version"] !== 1 || typeof record["sessionId"] !== "string" || typeof record["attempt"] !== "number") {
    return null;
  }
  const verdicts: Record<string, EffectVerdict> = {};
  const rawVerdicts = record["verdicts"];
  if (rawVerdicts !== null && typeof rawVerdicts === "object" && !Array.isArray(rawVerdicts)) {
    for (const [key, value] of Object.entries(rawVerdicts)) {
      if (value === "realized" || value === "absent") verdicts[key] = value;
    }
  }
  // `at` and `mode` are diagnostic here, never a safety input: the guardrail
  // acts on `attempt`, `sessionId` and `verdicts` alone. Repairing a missing
  // `at` is therefore honest, while DISCARDING the state would silently drop
  // the verdicts and leave the session unguarded — the one fallback that is
  // never allowed. A state missing any safety-bearing field is refused above.
  return {
    version: 1,
    attempt: record["attempt"],
    sessionId: record["sessionId"],
    mode: record["mode"] === "resume" ? "resume" : "new",
    verdicts,
    at: typeof record["at"] === "string" ? record["at"] : "",
  };
}

// ---- the persisted continuity pause ----

export function writePause(workDir: string, pause: PauseRecord): void {
  // The evidence outlives the record: a corrupt pause is moved aside, never
  // overwritten, so the operator can still inspect what the factory read.
  if (readValidPause(workDir) === null && existsSync(join(workDir, PAUSE_FILENAME))) {
    renameSync(join(workDir, PAUSE_FILENAME), freePath(join(workDir, `${PAUSE_FILENAME}.unreadable`)));
  }
  writeAtomic(join(workDir, PAUSE_FILENAME), pause);
}

/** The first `<path>`, `<path>.2`, `<path>.3`… the filesystem does not hold:
 *  every corrupt record is kept, none is overwritten. */
function freePath(path: string): string {
  let candidate = path;
  for (let index = 2; existsSync(candidate); index += 1) candidate = `${path}.${index}`;
  return candidate;
}

/**
 * The persisted pause. A file that exists but cannot be read as a pause is
 * NOT "no pause": returning absent would let the work fall back to a recovery
 * (which the record's author asked it not to do), spend the budget and post a
 * second help request. It is reported as the doubt it is — reason
 * `record-unreadable` — and matches whichever attempt is current, because the
 * record that would have said which one is exactly what is missing.
 */
export function readPause(workDir: string): PauseRecord | null {
  const valid = readValidPause(workDir);
  if (valid !== null) return valid;
  if (!existsSync(join(workDir, PAUSE_FILENAME))) return null;
  return {
    version: 1,
    work: { repo: "", number: 0 },
    attempt: 0,
    reason: "record-unreadable",
    detail: `the pause record at ${PAUSE_FILENAME} could not be read; its original is preserved beside it`,
    at: "",
  };
}

/** Does a pause wait for the current attempt? A record whose own attempt is
 *  unreadable matches any attempt: the doubt is not resolved by guessing one. */
export function pauseWaits(pause: PauseRecord, attempt: number): boolean {
  return pause.reason === "record-unreadable" || pause.attempt === attempt;
}

function readValidPause(workDir: string): PauseRecord | null {
  const raw = readIfExists(join(workDir, PAUSE_FILENAME));
  if (raw === null) return null;
  const record = parseJsonObject(raw);
  if (record === null) return null;
  // A record naming a reason this factory does not know belongs to a version
  // it cannot interpret: `record-unreadable` says so instead of discarding the
  // fact that a pause was asked for.
  if (record["version"] !== 1) return null;
  if (typeof record["attempt"] !== "number") return null;
  const reason = record["reason"];
  if (typeof reason !== "string" || !KNOWN_PAUSE_REASONS.has(reason)) return null;
  // `record-unreadable` is the one reason whose attempt is honestly unknown
  // (0). Every other pause must name the attempt it waits for.
  if (reason !== "record-unreadable" && record["attempt"] < 1) return null;
  const work = record["work"];
  if (work === null || typeof work !== "object" || Array.isArray(work)) return null;
  const workRecord = work as Record<string, unknown>;
  if (typeof workRecord["repo"] !== "string" || typeof workRecord["number"] !== "number") return null;
  return {
    version: 1,
    work: { repo: workRecord["repo"], number: workRecord["number"] },
    attempt: record["attempt"],
    reason: reason as PauseReason,
    detail: typeof record["detail"] === "string" ? record["detail"] : "",
    at: typeof record["at"] === "string" ? record["at"] : "",
    ...(typeof record["sessionId"] === "string" ? { sessionId: record["sessionId"] } : {}),
    ...(record["announced"] === true ? { announced: true } : {}),
  };
}

export function clearPause(workDir: string): void {
  const path = join(workDir, PAUSE_FILENAME);
  if (existsSync(path)) renameSync(path, `${path}.resolved`);
  const unreadable = join(workDir, `${PAUSE_FILENAME}.unreadable`);
  if (existsSync(unreadable)) renameSync(unreadable, `${unreadable}.resolved`);
}

// ---- fs primitives ----

/** Append one JSON line and fsync it: the caller can act right after. */
function appendDurable(path: string, value: unknown): void {
  mkdirSync(dirname(path), { recursive: true });
  const fd = openSync(path, "a");
  try {
    writeSync(fd, `${JSON.stringify(value)}\n`);
    fsyncSync(fd);
  } finally {
    closeSync(fd);
  }
}

function writeAtomic(path: string, value: unknown): void {
  mkdirSync(dirname(path), { recursive: true });
  const temp = `${path}.tmp`;
  const fd = openSync(temp, "w");
  try {
    writeSync(fd, `${JSON.stringify(value, null, 2)}\n`);
    fsyncSync(fd);
  } finally {
    closeSync(fd);
  }
  renameSync(temp, path);
}

function readIfExists(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function isSessionLink(value: unknown): value is SessionLink {
  if (value === null || typeof value !== "object") return false;
  const record = value as Record<string, unknown>;
  const work = record["work"];
  if (work === null || typeof work !== "object") return false;
  const workRecord = work as Record<string, unknown>;
  return (
    record["version"] === 1 &&
    typeof workRecord["repo"] === "string" &&
    typeof workRecord["number"] === "number" &&
    typeof record["attempt"] === "number" &&
    typeof record["round"] === "number" &&
    (record["mode"] === "new" || record["mode"] === "resume") &&
    typeof record["sessionId"] === "string" &&
    typeof record["at"] === "string"
  );
}

function isJournalLine(value: unknown): value is JournalLine {
  if (value === null || typeof value !== "object") return false;
  const record = value as Record<string, unknown>;
  const type = record["type"];
  if (type === "session-start") {
    return typeof record["attempt"] === "number" && typeof record["sessionId"] === "string";
  }
  if (type === "intent") {
    return (
      typeof record["seq"] === "number" &&
      typeof record["attempt"] === "number" &&
      typeof record["sessionId"] === "string" &&
      typeof record["callId"] === "string" &&
      (record["safety"] === "effect" || record["safety"] === "unknown") &&
      Array.isArray(record["actions"])
    );
  }
  if (type === "result") {
    return (
      typeof record["seq"] === "number" &&
      typeof record["attempt"] === "number" &&
      typeof record["sessionId"] === "string" &&
      typeof record["callId"] === "string" &&
      typeof record["ok"] === "boolean"
    );
  }
  return false;
}
